export type StringKey = keyof typeof defaults;

let overrides: Partial<Record<StringKey, string>> = {};

export function setStringOverrides(values: Partial<Record<StringKey, string>>): void {
  overrides = values;
}

type Plural<K> = K extends `${infer Base}.one` ? Base : never;

/** Libellé au singulier (n ≤ 1) ou au pluriel : clés « <base>.one » et « <base>.many ». */
export function tn(base: Plural<StringKey>, n: number, params: Record<string, string | number> = {}): string {
  return t(`${base}.${n <= 1 ? "one" : "many"}` as StringKey, { n, ...params });
}

export function t(key: StringKey, params: Record<string, string | number> = {}): string {
  const template = overrides[key] ?? defaults[key];
  return typo(template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`)));
}
